import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';

const base = process.env.TEST_URL || 'http://127.0.0.1:5173';
const artifacts = 'artifacts/menu-update';
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ channel: process.env.TEST_BROWSER || 'msedge', headless: true });
const results = [];
try {
  for (const [width, height] of [[320, 720], [390, 844], [1440, 1000]]) {
    const context = await browser.newContext({ viewport: { width, height } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    await page.goto(base);
    await page.locator('#hero-title').waitFor();
    await page.waitForFunction(() => document.querySelector('.hero__media').readyState >= 2);
    const cta = page.locator('.hero__actions a');
    const rect = await cta.boundingBox();
    assert.ok(rect.y >= 0 && rect.y + rect.height <= height, `PEDIR visible at ${width}`);
    assert.equal(await cta.innerText(), 'PEDIR');
    assert.match(await page.locator('#hero-title').innerText(), /hambre/i);
    assert.equal(await page.locator('.brand-header__logo img').evaluate(image => image.complete && image.naturalWidth > 0), true);
    assert.equal(await page.locator('.hero + .brand-tape').count(), 1);
    assert.equal(await page.locator('.brand-tape').count(), 1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: `${artifacts}/home-${width}.png` });
    await page.locator('#ubicacion').scrollIntoViewIfNeeded();
    await page.waitForTimeout(800);
    assert.match(await page.locator('.location iframe').getAttribute('src'), /google.com\/maps/);
    assert.equal(await page.locator('.location__details a').first().getAttribute('href').then(url => url.startsWith('https://www.google.com/maps/dir/')), true);
    await cta.click();
    await page.waitForURL('**/delivery');
    await page.locator('#product-bbq-beast').waitFor();
    // The real catalog and stock are loaded from Supabase for purchase-flow checks.
    assert.equal(await page.locator('#product-extra-0').count(), 0);
    await page.locator('#product-bbq-beast .menu-item-add').click();
    const modal = page.locator('.product-configurator');
    await modal.getByRole('button', { name: /^Doble/ }).click();
    const meat = modal.getByRole('button', { name: 'Agregar Extras de tu hamburguesa: Extra carne y cheddar', exact: true });
    const bacon = modal.getByRole('button', { name: 'Agregar Extras de tu hamburguesa: Tocino', exact: true });
    for (let i = 0; i < 2; i++) await meat.click();
    for (let i = 0; i < 3; i++) await bacon.click();
    await modal.getByRole('button', { name: 'Agregar MEJORA TUS PAPAS: Salsa cheddar', exact: true }).click();
    assert.match(await modal.locator('.product-configurator__submit').innerText(), /20\.390/);
    for (let i = 0; i < 8; i++) await meat.click();
    assert.match(await modal.locator('.product-configurator__submit').innerText(), /40\.390/);
    for (let i = 0; i < 8; i++) await modal.getByRole('button', { name: 'Quitar Extras de tu hamburguesa: Extra carne y cheddar', exact: true }).click();
    await modal.getByRole('button', { name: 'Quitar MEJORA TUS PAPAS: Salsa cheddar', exact: true }).click();
    assert.match(await modal.locator('.product-configurator__submit').innerText(), /19\.390/);
    const submitRect = await modal.locator('.product-configurator__submit').boundingBox();
    assert.ok(submitRect.y >= 0 && submitRect.y + submitRect.height <= height);
    await page.screenshot({ path: `${artifacts}/burger-${width}.png` });
    await modal.locator('.product-configurator__submit').click();
    await page.locator('.cart-item').first().waitFor();
    assert.equal(await page.locator('.cart-item').count(), 1);
    assert.match(await page.locator('.cart-item').innerText(), /2 × Extra carne y cheddar/);
    assert.match(await page.locator('.cart-item').innerText(), /3 × Tocino/);
    await page.locator('.cart-drawer__header').getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.locator('#product-tentacion .menu-item-add').click();
    const sections = modal.locator('.promo-burger');
    await sections.nth(0).locator('select').selectOption('bbq-beast');
    await sections.nth(1).locator('select').selectOption('onion-shet');
    await sections.nth(0).getByRole('button', { name: 'Agregar Hamburguesa 1: extras: Extra carne y cheddar', exact: true }).click();
    await sections.nth(0).getByRole('button', { name: 'Agregar Hamburguesa 1: extras: Extra carne y cheddar', exact: true }).click();
    await sections.nth(1).getByRole('button', { name: 'Agregar Hamburguesa 2: extras: Tocino', exact: true }).click();
    assert.match(await modal.locator('.product-configurator__submit').innerText(), /24\.790/);
    await modal.locator('.product-configurator__submit').click();
    await page.locator('.cart-item').nth(1).waitFor();
    assert.equal(await page.locator('.cart-item').count(), 2);
    assert.match(await page.locator('.cart-item').nth(1).innerText(), /Hamburguesa 1 · Extra hamburguesa: 2 × Extra carne y cheddar/);
    assert.match(await page.locator('.cart-item').nth(1).innerText(), /Hamburguesa 2 · Extra hamburguesa: 1 × Tocino/);
    await page.locator('.cart-drawer__header').getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.locator('#product-extra-6 .menu-item-add').click();
    await page.locator('.cart-item').nth(2).waitFor();
    assert.match(await page.locator('.cart-item').nth(2).innerText(), /Extra independiente: enviar por separado/);
    await page.locator('.cart-drawer__header').getByRole('button', { name: 'Cerrar', exact: true }).click();
    const drink = page.locator('#product-bebida-0');
    await drink.getByRole('button', { name: 'Agregar Coca Cola', exact: true }).click();
    await drink.getByRole('button', { name: 'Agregar Coca Cola', exact: true }).click();
    assert.equal(await drink.locator('output').innerText(), '3');
    await drink.locator('.menu-item-add').click();
    await page.locator('.cart-item').nth(3).waitFor();
    assert.equal(await page.locator('.cart-item').nth(3).locator('.cart-quantity > span').innerText(), '3');
    await page.locator('.cart-item').nth(3).getByRole('button', { name: 'Agregar una unidad de Coca Cola', exact: true }).click();
    assert.equal(await page.locator('.cart-item').nth(3).locator('.cart-quantity > span').innerText(), '4');
    await page.screenshot({ path: `${artifacts}/cart-${width}.png` });
    await page.locator('.cart-drawer__header').getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.locator('#product-jugo-jumex').getByRole('button', { name: 'Agregar Jugo Jumex', exact: true }).click();
    await page.locator('#product-jugo-jumex .menu-item-add').click();
    await modal.getByRole('button', { name: 'Manzana', exact: true }).click();
    assert.match(await modal.locator('.product-configurator__submit').innerText(), /3\.000/);
    await modal.getByRole('button', { name: 'Cerrar', exact: true }).click();
    // Isolated response overrides exercise UI states without changing production stock.
    await page.route('**/rest/v1/product_availability*', async route => {
      const response = await route.fetch(); const rows = await response.json();
      const ids = new Set(['bbq-beast', 'extra-0', 'extra-6', 'bebida-0']);
      await route.fulfill({ json: [...rows.filter(item => !ids.has(item.product_id)), ...[...ids].map(product_id => ({ product_id, available: false }))] });
    });
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#product-bbq-beast .menu-item-add')?.disabled);
    assert.equal(await page.locator('#product-bbq-beast .menu-item-add').isDisabled(), true);
    assert.equal(await page.locator('#product-bebida-0 .quantity-control button').last().isDisabled(), true);
    await page.locator('#product-onion-shet .menu-item-add').click();
    assert.equal(await modal.getByRole('button', { name: 'Agregar Extras de tu hamburguesa: Extra carne y cheddar', exact: true }).isDisabled(), true);
    assert.match(await modal.locator('.extra-quantities').last().innerText(), /SIN STOCK/);
    await modal.getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.locator('#product-tentacion .menu-item-add').click();
    assert.equal(await modal.locator('option[value="bbq-beast"]').count(), 0);
    await modal.getByRole('button', { name: 'Cerrar', exact: true }).click();
    await page.unroute('**/rest/v1/product_availability*');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#product-bbq-beast .menu-item-add')?.disabled === false);
    await page.route('**/rest/v1/store_settings*', async route => {
      const response = await route.fetch(); await route.fulfill({ json: { ...await response.json(), is_open: false } });
    });
    await page.reload();
    await page.locator('.closed-popup').waitFor();
    await page.screenshot({ path: `${artifacts}/closed-${width}.png` });
    await page.getByRole('button', { name: 'Cerrar aviso', exact: true }).click();
    assert.equal(await page.locator('#product-bbq-beast .menu-item-add').isDisabled(), true);
    assert.equal(await page.locator('.whatsapp-button').getAttribute('href'), 'https://wa.me/56956901911?text=Hola%2C%20quiero%20hacer%20una%20consulta');
    assert.deepEqual(errors, [], `Console at ${width}`);
    results.push({ width, height, status: 'passed', consoleErrors: errors });
    await context.close();
  }
  await writeFile(`${artifacts}/results.json`, JSON.stringify(results, null, 2));
  console.log(JSON.stringify(results, null, 2));
} finally { await browser.close(); }
